/** The lines to add to payload.config.ts. */
export const configSnippet = (
  slugs: CollectionSlugs,
  importPath: string,
): string => `import { seoPlugin } from '@payloadcms/plugin-seo'
import { redirectsPlugin } from '@payloadcms/plugin-redirects'
import { wpCollections } from '${importPath}'

export default buildConfig({
  collections: [...wpCollections /* , your other collections */],
  plugins: [
    seoPlugin({ collections: [${q(slugs.posts)}, ${q(slugs.pages)}], uploadsCollection: ${q(slugs.media)} }),
    redirectsPlugin({ collections: [${q(slugs.posts)}, ${q(slugs.pages)}] }),
  ],
})`
