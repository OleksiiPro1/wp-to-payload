import type { AcfCollectionPlan, AcfPlan } from '../acf/plan.js'
import type { CollectionSlugs } from '../config.js'
import { acfFieldLines, needsEditor } from './acf-fields.js'

/** Collection files written by `scaffold`. They belong to the user's project afterwards. */
export interface ScaffoldFile {
  name: string
  content: string
}

/** A relationship field for the terms of a taxonomy. */
export interface ScaffoldRelation {
  field: string
  collection: string
}

/** A collection for a custom post type or taxonomy. */
export interface ScaffoldCollection {
  slug: string
  /** The WordPress post type or taxonomy, for the comment in the file. */
  wpName: string
  hierarchical: boolean
}

export interface ScaffoldPostType extends ScaffoldCollection {
  /** Fields for the taxonomies its items use. */
  relations: ScaffoldRelation[]
}

/** Custom post types and taxonomies of the export, with the collection slugs to use. */
export interface ScaffoldCustom {
  postTypes: ScaffoldPostType[]
  taxonomies: ScaffoldCollection[]
  /** Fields for custom taxonomies on posts and on pages. */
  postRelations: ScaffoldRelation[]
  pageRelations: ScaffoldRelation[]
}

/** Languages of a multilingual site: fields get a value per locale. */
export interface ScaffoldLocalization {
  /** Payload locale codes with a label, the default first. */
  locales: { code: string; label: string }[]
  defaultLocale: string
}

/** Globals for menus, with `navItems` links shaped like those of Payload's website template. */
export interface ScaffoldGlobals {
  /** Global slugs, such as `header` and `footer`. */
  slugs: string[]
  /** Collections a menu entry can link to. */
  documents: string[]
}

export const NO_CUSTOM: ScaffoldCustom = {
  postTypes: [],
  taxonomies: [],
  postRelations: [],
  pageRelations: [],
}

const header = `// Generated by wp-to-payload scaffold. This file is yours: change it as you like.
// Keep the wpId field: it lets \`wp-to-payload import\` update documents instead of duplicating them.
`

const q = (value: string) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

const BUILTIN_NAMES = ['Authors', 'Categories', 'Media', 'Pages', 'Posts', 'Tags']

/** Export names for the custom collections: `recipe-categories` → `RecipeCategories`. */
const exportNames = (custom: ScaffoldCustom): Map<string, string> => {
  const taken = new Set(BUILTIN_NAMES)
  const names = new Map<string, string>()
  for (const { slug } of [...custom.taxonomies, ...custom.postTypes]) {
    const words = slug.split(/[^a-zA-Z0-9]+/).filter(Boolean)
    let name = words.map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('') || 'Collection'
    if (!/^[A-Za-z]/.test(name)) name = `Wp${name}`
    const base = name
    for (let n = 2; taken.has(name); n++) name = `${base}${n}`
    taken.add(name)
    names.set(slug, name)
  }
  return names
}

const relationFields = (relations: ScaffoldRelation[]): string =>
  relations
    .map(
      (r) => `    {
      name: ${q(r.field)},
      type: 'relationship',
      relationTo: ${q(r.collection)},
      hasMany: true,
      admin: { position: 'sidebar' },
    },
`,
    )
    .join('')

/** A collection for posts, pages or a custom post type: drafts and the WordPress fields. */
const documentCollection = (o: {
  exportName: string
  slug: string
  slugs: CollectionSlugs
  hierarchical: boolean
  relations: ScaffoldRelation[]
  wpName?: string
  /** `, localized: true` on multilingual sites, else empty. */
  loc: string
  acf?: AcfCollectionPlan
}): string => `${header}import type { CollectionConfig } from 'payload'
import { wpEditor } from './editor'
import { slug, wpId${o.loc ? ', wpIds' : ''} } from './fields'
${o.wpName ? `\n/** The WordPress post type "${o.wpName}". */` : ''}
export const ${o.exportName}: CollectionConfig = {
  slug: ${q(o.slug)},
  access: {
    read: ({ req }) => (req.user ? true : { _status: { equals: 'published' } }),
  },
  admin: { useAsTitle: 'title', defaultColumns: ['title', 'slug', ${o.hierarchical ? "'parent'" : "'publishedAt'"}, '_status'] },
  versions: { drafts: true },
  fields: [
    { name: 'title', type: 'text', required: true${o.loc} },
${
  o.hierarchical
    ? `    // Not unique: WordPress allows the same slug under different parents.\n    slug(false${o.loc ? ', true' : ''}),`
    : `    slug(true${o.loc ? ', true' : ''}),`
}
    { name: 'content', type: 'richText', editor: wpEditor${o.loc} },
    { name: 'excerpt', type: 'textarea'${o.loc} },
    { name: 'featuredImage', type: 'upload', relationTo: ${q(o.slugs.media)}${o.loc} },
${
  o.hierarchical
    ? `    { name: 'parent', type: 'relationship', relationTo: ${q(o.slug)}, admin: { position: 'sidebar' } },\n`
    : ''
}    { name: 'publishedAt', type: 'date', admin: { position: 'sidebar' } },
    { name: 'author', type: 'relationship', relationTo: ${q(o.slugs.authors)}, admin: { position: 'sidebar' } },
${relationFields(o.relations)}${acfFieldLines(o.acf)}    wpId,
${o.loc ? '    wpIds,\n' : ''}  ],
}
`

/** A collection for categories, tags or a custom taxonomy. */
const termCollection = (o: {
  exportName: string
  slug: string
  hierarchical: boolean
  wpName?: string
  loc: string
  acf?: AcfCollectionPlan
}): string => `${header}import type { CollectionConfig } from 'payload'
${o.acf && needsEditor(o.acf.fields) ? "import { wpEditor } from './editor'\n" : ''}import { slug, wpId${o.loc ? ', wpIds' : ''} } from './fields'
${o.wpName ? `\n/** The WordPress taxonomy "${o.wpName}". */` : ''}
export const ${o.exportName}: CollectionConfig = {
  slug: ${q(o.slug)},
  access: { read: () => true },
  admin: { useAsTitle: 'title', defaultColumns: ['title', 'slug'${o.hierarchical ? ", 'parent'" : ''}] },
  fields: [
    { name: 'title', type: 'text', required: true${o.loc} },
    slug(true${o.loc ? ', true' : ''}),
    { name: 'description', type: 'textarea'${o.loc} },
${
  o.hierarchical
    ? `    { name: 'parent', type: 'relationship', relationTo: ${q(o.slug)}, admin: { position: 'sidebar' } },\n`
    : ''
}${acfFieldLines(o.acf)}    wpId,
${o.loc ? '    wpIds,\n' : ''}  ],
}
`

/** Export names for globals: `header` → `Header`, unless a collection has that name. */
const globalNames = (
  globals: ScaffoldGlobals | undefined,
  taken: string[],
): Map<string, string> => {
  const used = new Set(taken)
  const names = new Map<string, string>()
  for (const slug of globals?.slugs ?? []) {
    const words = slug.split(/[^a-zA-Z0-9]+/).filter(Boolean)
    let name = words.map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('') || 'Menu'
    if (!/^[A-Za-z]/.test(name)) name = `Wp${name}`
    if (used.has(name)) name = `${name}Global`
    const base = name
    for (let n = 2; used.has(name); n++) name = `${base}${n}`
    used.add(name)
    names.set(slug, name)
  }
  return names
}

const linkField = (documents: string[]) => `
/** A link in a menu, shaped like the link field of Payload's website template. */
export const link: Field = {
  name: 'link',
  type: 'group',
  fields: [
    {
      type: 'row',
      fields: [
        {
          name: 'type',
          type: 'radio',
          defaultValue: 'reference',
          options: [
            { label: 'Internal link', value: 'reference' },
            { label: 'Custom URL', value: 'custom' },
          ],
          admin: { layout: 'horizontal', width: '50%' },
        },
        { name: 'newTab', type: 'checkbox', label: 'Open in new tab', admin: { width: '50%' } },
      ],
    },
    {
      type: 'row',
      fields: [
        {
          name: 'reference',
          type: 'relationship',
          relationTo: [${documents.map(q).join(', ')}],
          label: 'Document to link to',
          admin: {
            condition: (_, siblingData) => siblingData?.type === 'reference',
            width: '50%',
          },
        },
        {
          name: 'url',
          type: 'text',
          label: 'Custom URL',
          admin: { condition: (_, siblingData) => siblingData?.type === 'custom', width: '50%' },
        },
        { name: 'label', type: 'text', label: 'Label', required: true, admin: { width: '50%' } },
      ],
    },
  ],
}
`

const globalFile = (exportName: string, slug: string, loc: string): string => `${header.replace(
  /\n\/\/ Keep the wpId field.*\n$/,
  '\n',
)}import type { GlobalConfig } from 'payload'
import { link } from './fields'

/** A menu from WordPress. \`wp-to-payload import\` writes its entries into navItems. */
export const ${exportName}: GlobalConfig = {
  slug: ${q(slug)},
  access: { read: () => true },
  fields: [
    {
      name: 'navItems',
      type: 'array',${loc ? '\n      localized: true,' : ''}
      fields: [link],
    },
  ],
}
`

export const scaffoldFiles = (
  slugs: CollectionSlugs,
  custom: ScaffoldCustom = NO_CUSTOM,
  localization?: ScaffoldLocalization,
  acf?: AcfPlan,
  globals?: ScaffoldGlobals,
): ScaffoldFile[] => {
  const loc = localization ? ', localized: true' : ''
  const acfOf = (slug: string) => acf?.collections.get(slug)
  const names = exportNames(custom)
  const nameOf = (slug: string) => names.get(slug) ?? slug
  const taxonomyNames = custom.taxonomies.map((t) => nameOf(t.slug))
  const typeNames = custom.postTypes.map((t) => nameOf(t.slug))
  const globalExports = globalNames(globals, [...BUILTIN_NAMES, ...taxonomyNames, ...typeNames])
  const allNames = [
    ...BUILTIN_NAMES,
    ...taxonomyNames,
    ...typeNames,
    ...globalExports.values(),
  ].sort()
  return [
    {
      name: 'fields.ts',
      content: `${header}import type { Field } from 'payload'

/** The WordPress ID of the imported item. */
export const wpId: Field = {
  name: 'wpId',
  type: 'number',
  index: true,
  admin: {
    position: 'sidebar',
    readOnly: true,
    description: 'WordPress ID, set by wp-to-payload',
  },
}

export const slug = (unique: boolean${loc ? ', localized = false' : ''}): Field => ({
  name: 'slug',
  type: 'text',
  required: true,
  index: true,
  unique,${loc ? '\n  // Unique per locale: each language version has a slug of its own.\n  localized,' : ''}
  admin: { position: 'sidebar' },
})
${
  loc
    ? `
/** The WordPress IDs of all language versions of a translated document. */
export const wpIds: Field = {
  name: 'wpIds',
  type: 'number',
  hasMany: true,
  index: true,
  admin: {
    position: 'sidebar',
    readOnly: true,
    description: 'WordPress IDs of all languages, set by wp-to-payload',
  },
}
`
    : ''
}${globals && globals.slugs.length > 0 ? linkField(globals.documents) : ''}`,
    },
    {
      name: 'editor.ts',
      content: `${header}import type { Block } from 'payload'
import {
  BlocksFeature,
  CodeBlock,
  EXPERIMENTAL_TableFeature,
  lexicalEditor,
} from '@payloadcms/richtext-lexical'

/** Embedded media (YouTube, Vimeo, …) from WordPress embed blocks. */
export const Embed: Block = {
  slug: 'embed',
  labels: { singular: 'Embed', plural: 'Embeds' },
  fields: [
    { name: 'url', type: 'text', required: true },
    { name: 'provider', type: 'text' },
  ],
}

/** Payload's default features plus code blocks, embeds and tables. */
export const wpEditor = lexicalEditor({
  features: ({ defaultFeatures }) => [
    ...defaultFeatures,
    BlocksFeature({ blocks: [CodeBlock(), Embed] }),
    EXPERIMENTAL_TableFeature(),
  ],
})
`,
    },
    {
      name: 'Media.ts',
      content: `${header}import type { CollectionConfig } from 'payload'
import { wpId${loc ? ', wpIds' : ''} } from './fields'

export const Media: CollectionConfig = {
  slug: ${q(slugs.media)},
  access: { read: () => true },
  upload: true,
  fields: [
    { name: 'alt', type: 'text', required: true${loc} },
    { name: 'caption', type: 'textarea'${loc} },
    wpId,${loc ? '\n    wpIds,' : ''}
  ],
}
`,
    },
    {
      name: 'Categories.ts',
      content: termCollection({
        exportName: 'Categories',
        slug: slugs.categories,
        hierarchical: true,
        loc,
        acf: acfOf(slugs.categories),
      }),
    },
    {
      name: 'Tags.ts',
      content: termCollection({
        exportName: 'Tags',
        slug: slugs.tags,
        hierarchical: false,
        loc,
        acf: acfOf(slugs.tags),
      }),
    },
    ...custom.taxonomies.map((t) => ({
      name: `${nameOf(t.slug)}.ts`,
      content: termCollection({
        exportName: nameOf(t.slug),
        slug: t.slug,
        hierarchical: t.hierarchical,
        wpName: t.wpName,
        loc,
        acf: acfOf(t.slug),
      }),
    })),
    {
      name: 'Authors.ts',
      content: `${header}import type { CollectionConfig } from 'payload'
import { slug, wpId } from './fields'

/** Bylines. Not login accounts: WordPress passwords and roles are never imported. */
export const Authors: CollectionConfig = {
  slug: ${q(slugs.authors)},
  access: { read: () => true },
  admin: { useAsTitle: 'name', defaultColumns: ['name', 'slug'] },
  fields: [
    { name: 'name', type: 'text', required: true },
    slug(true),
    { name: 'bio', type: 'textarea' },
    // Only filled when wp-to-payload.config.json sets "importAuthorEmails": true.
    { name: 'email', type: 'email', admin: { position: 'sidebar' } },
    wpId,
  ],
}
`,
    },
    {
      name: 'Posts.ts',
      content: documentCollection({
        exportName: 'Posts',
        slug: slugs.posts,
        slugs,
        hierarchical: false,
        relations: [
          { field: 'categories', collection: slugs.categories },
          { field: 'tags', collection: slugs.tags },
          ...custom.postRelations,
        ],
        loc,
        acf: acfOf(slugs.posts),
      }),
    },
    {
      name: 'Pages.ts',
      content: documentCollection({
        exportName: 'Pages',
        slug: slugs.pages,
        slugs,
        hierarchical: true,
        relations: custom.pageRelations,
        loc,
        acf: acfOf(slugs.pages),
      }),
    },
    ...custom.postTypes.map((t) => ({
      name: `${nameOf(t.slug)}.ts`,
      content: documentCollection({
        exportName: nameOf(t.slug),
        slug: t.slug,
        slugs,
        hierarchical: t.hierarchical,
        relations: t.relations,
        wpName: t.wpName,
        loc,
        acf: acfOf(t.slug),
      }),
    })),
    ...[...globalExports].map(([slug, name]) => ({
      name: `${name}.ts`,
      content: globalFile(name, slug, loc),
    })),
    {
      name: 'index.ts',
      content: `${header}${allNames.map((n) => `import { ${n} } from './${n}'`).join('\n')}

export ${wrapped('{', allNames, '}')}

/** All collections for a site imported from WordPress. */
export const wpCollections = ${wrapped(
        '[',
        [
          'Media',
          'Categories',
          'Tags',
          ...taxonomyNames,
          'Authors',
          'Posts',
          'Pages',
          ...typeNames,
        ],
        ']',
      )}
${
  globalExports.size > 0
    ? `
/** Globals for the WordPress menus. */
export const wpGlobals = ${wrapped('[', [...globalExports.values()], ']')}
`
    : ''
}`,
    },
  ]
}

/** `{ A, B }` on one line, or one name per line when that gets long. */
const wrapped = (open: string, names: string[], close: string): string => {
  const line = `${open}${open === '{' ? ' ' : ''}${names.join(', ')}${close === '}' ? ' ' : ''}${close}`
  return line.length <= 80 ? line : `${open}\n${names.map((n) => `  ${n},`).join('\n')}\n${close}`
}

/** The lines to add to payload.config.ts. */
export const configSnippet = (
  slugs: CollectionSlugs,
  importPath: string,
  custom: ScaffoldCustom = NO_CUSTOM,
  localization?: ScaffoldLocalization,
  globals = false,
): string => {
  const documents = [slugs.posts, slugs.pages, ...custom.postTypes.map((t) => t.slug)]
    .map(q)
    .join(', ')
  const locales = localization
    ? `
  localization: {
    locales: [
${localization.locales.map((l) => `      { label: ${q(l.label)}, code: ${q(l.code)} },`).join('\n')}
    ],
    defaultLocale: ${q(localization.defaultLocale)},
    fallback: true,
  },`
    : ''
  return `import { seoPlugin } from '@payloadcms/plugin-seo'
import { redirectsPlugin } from '@payloadcms/plugin-redirects'
import { wpCollections${globals ? ', wpGlobals' : ''} } from '${importPath}'

export default buildConfig({
  collections: [...wpCollections /* , your other collections */],${globals ? '\n  globals: [...wpGlobals /* , your other globals */],' : ''}${locales}
  plugins: [
    seoPlugin({ collections: [${documents}], uploadsCollection: ${q(slugs.media)} }),
    redirectsPlugin({ collections: [${documents}] }),
  ],
})`
}
