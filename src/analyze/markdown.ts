import type { AnalyzeReport, Detection } from './report.js'

const SUPPORT_LABEL = {
  supported: '✅ converted',
  partial: '⚠️ partly converted',
  dropped: '❌ removed',
  unknown: '❌ no converter (content kept as HTML)',
} as const

const formatBytes = (bytes: number): string =>
  bytes >= 1024 * 1024
    ? `${(bytes / 1024 / 1024).toFixed(1)} MB`
    : `${Math.max(1, Math.round(bytes / 1024))} KB`

const escapeCell = (value: string | number): string =>
  String(value).replace(/\|/g, '\\|').replace(/\n/g, ' ')

const tableOf = (header: string[], rows: (string | number)[][]): string[] => [
  `| ${header.join(' | ')} |`,
  `| ${header.map(() => '---').join(' | ')} |`,
  ...rows.map((r) => `| ${r.map(escapeCell).join(' | ')} |`),
]

const statusText = (byStatus: Record<string, number>): string =>
  Object.entries(byStatus)
    .map(([status, n]) => `${n} ${status}`)
    .join(', ') || '–'

const detectionRow = (name: string, d: Detection, note: string): (string | number)[] => [
  name,
  d.detected ? 'yes' : 'no',
  d.detected ? d.items : '–',
  d.detected ? note : '',
]

/** Renders the analysis report as Markdown for people (report.json holds the same data). */
export const renderMarkdown = (r: AnalyzeReport): string => {
  const lines: string[] = []
  const push = (...l: string[]) => lines.push(...l)

  push(`# WordPress export analysis: ${r.site.title || r.site.url || r.source.file}`, '')
  push(
    `Generated by ${r.tool.name} ${r.tool.version} on ${r.generatedAt.slice(0, 10)} from \`${r.source.file}\` (${formatBytes(r.source.bytes)}).`,
    '',
  )

  push('## Summary', '')
  push(
    ...tableOf(
      ['', ''],
      [
        ['Site', r.site.url || '–'],
        ['Language', r.site.language || '–'],
        ['WordPress', r.site.wordpressVersion ?? 'unknown'],
        ['WXR version', r.site.wxrVersion || '–'],
        ['Multisite', r.site.multisite ? 'yes' : 'no'],
        ['Complexity', `**${r.complexity.level}** (score ${r.complexity.score})`],
      ],
    ),
    '',
  )

  push('## Complexity', '')
  if (r.complexity.reasons.length === 0) {
    push('Nothing unusual found: standard posts, pages, media and taxonomies.', '')
  } else {
    push(
      ...tableOf(
        ['Points', 'Reason'],
        r.complexity.reasons.map((x) => [x.points, x.reason]),
      ),
      '',
    )
  }
  push(
    'Score: 0–2 simple, 3–5 medium, 6 or more complex. Page builders, WooCommerce and multilingual content always count as complex.',
    '',
  )

  push('## Content', '')
  const c = r.counts
  const rows: (string | number)[][] = [
    ['Posts', c.posts.total, statusText(c.posts.byStatus)],
    ['Pages', c.pages.total, statusText(c.pages.byStatus)],
    ['Media files', c.attachments, ''],
    ['Categories', c.categories, ''],
    ['Tags', c.tags, ''],
    ['Authors', c.authors, ''],
    ['Comments', c.comments, 'not migrated'],
    ['Menu items', c.menuItems, 'not migrated'],
  ]
  push(...tableOf(['Type', 'Count', 'Notes'], rows), '')
  push(
    `Editor: ${r.content.gutenbergItems} items use blocks (Gutenberg), ${r.content.classicItems} use the classic editor, ${r.content.emptyItems} are empty.` +
      (r.content.passwordProtected > 0
        ? ` ${r.content.passwordProtected} are password protected.`
        : ''),
    '',
  )

  push('## Custom post types and taxonomies', '')
  const { postTypes, taxonomies } = r.customTypes
  const importNote = (x: { imported: boolean; reason?: string }) =>
    x.imported ? '✅ own collection' : `❌ ${x.reason ?? 'not imported'}`
  const names = (list: string[]) => list.map((n) => `\`${n}\``).join(', ') || '–'
  if (postTypes.length === 0 && taxonomies.length === 0) {
    push('None: only posts, pages, categories and tags.', '')
  }
  if (postTypes.length > 0) {
    push(
      ...tableOf(
        ['Post type', 'Items', 'Statuses', 'Hierarchical', 'Taxonomies', 'Import'],
        postTypes.map((t) => [
          `\`${t.name}\``,
          t.items,
          statusText(t.byStatus),
          t.hierarchical ? 'yes' : 'no',
          names(t.taxonomies),
          importNote(t),
        ]),
      ),
      '',
    )
  }
  if (taxonomies.length > 0) {
    push(
      ...tableOf(
        ['Taxonomy', 'Terms', 'Hierarchical', 'Used by', 'Import'],
        taxonomies.map((t) => [
          `\`${t.name}\``,
          t.terms,
          t.hierarchical ? 'yes' : 'no',
          names(t.postTypes),
          importNote(t),
        ]),
      ),
      '',
    )
  }
  if (postTypes.some((t) => t.imported) || taxonomies.some((t) => t.imported)) {
    push(
      '`scaffold export.xml` writes a collection for each of them; the config file can map them to collections of your own.',
      '',
    )
  }

  push('## Gutenberg blocks', '')
  if (r.content.blocks.length === 0) push('No blocks found.', '')
  else {
    push(
      ...tableOf(
        ['Block', 'Uses', 'Items', 'Import'],
        r.content.blocks.map((b) => [`\`${b.name}\``, b.count, b.items, SUPPORT_LABEL[b.support]]),
      ),
      '',
    )
  }

  push('## Shortcodes', '')
  if (r.content.shortcodes.length === 0) push('No shortcodes found.', '')
  else {
    push(
      ...tableOf(
        ['Shortcode', 'Uses', 'Items'],
        r.content.shortcodes.map((s) => [`\`[${s.name}]\``, s.count, s.items]),
      ),
      '',
      'On import, `[caption]` and `[gallery]` are converted. Other shortcodes are removed, their text is kept, and each place is listed as a warning.',
      '',
    )
  }

  push('## Plugins and features', '')
  push(
    ...tableOf(
      ['Feature', 'Found', 'Items', 'Import'],
      [
        detectionRow('Elementor', r.builders.elementor, 'text kept, layout lost'),
        detectionRow('Divi', r.builders.divi, 'text kept, layout lost'),
        detectionRow('WPBakery', r.builders.wpbakery, 'text kept, layout lost'),
        detectionRow('Beaver Builder', r.builders.beaver, 'text kept, layout lost'),
        detectionRow('Oxygen', r.builders.oxygen, 'not migrated (content lives in builder data)'),
        detectionRow('Bricks', r.builders.bricks, 'not migrated (content lives in builder data)'),
        detectionRow('Avada', r.builders.avada, 'text kept, layout lost'),
        detectionRow('Yoast SEO', r.seo.yoast, 'title, description, image → meta'),
        detectionRow('Rank Math', r.seo.rankmath, 'title, description, image → meta'),
        detectionRow('All in One SEO', r.seo.aioseo, 'detected only'),
        detectionRow('SEOPress', r.seo.seopress, 'detected only'),
        detectionRow('WPML', r.multilingual.wpml, 'detected only'),
        detectionRow('Polylang', r.multilingual.polylang, 'detected only'),
        detectionRow('WooCommerce', r.woocommerce, 'detected only'),
        detectionRow('Advanced Custom Fields', r.acf, 'detected only'),
      ],
    ),
    '',
  )
  const languages = r.multilingual.polylang.details?.languages
  if (Array.isArray(languages) && languages.length > 0)
    push(`Polylang languages: ${languages.join(', ')}.`, '')
  if (r.acf.details)
    push(`ACF: ${r.acf.details.fieldGroups} field groups, ${r.acf.details.fields} fields.`, '')

  push('## Media', '')
  const media = Object.entries(r.media.byType).sort((a, b) => b[1] - a[1])
  if (media.length === 0) push('No media files.', '')
  else
    push(...tableOf(['Type', 'Files'], media), '', `Hosts: ${r.media.hosts.join(', ') || '–'}`, '')

  if (r.issues.length > 0) {
    push('## XML errors', '')
    push(`${r.issues.length} problems were skipped while reading the export.`, '')
    push(...r.issues.slice(0, 50).map((i) => `- line ${i.line}, column ${i.column}: ${i.message}`))
    if (r.issues.length > 50) push(`- … and ${r.issues.length - 50} more (see report.json)`)
    push('')
  }

  return `${lines.join('\n').trimEnd()}\n`
}
