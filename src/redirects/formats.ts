import type { Redirect } from './build.js'

export const FORMATS = ['csv', 'json', 'next', 'htaccess', 'nginx', 'netlify'] as const
export type RedirectFormat = (typeof FORMATS)[number]

/** Default file name per format when writing to a directory. */
export const FILE_NAMES: Record<RedirectFormat, string> = {
  csv: 'redirects.csv',
  json: 'redirects.json',
  next: 'next-redirects.json',
  htaccess: 'redirects.htaccess',
  nginx: 'redirects.nginx.conf',
  netlify: '_redirects',
}

/** Fully decoded path, as Apache and nginx see it when matching. */
const decode = (path: string): string =>
  path
    .split('/')
    .map((segment) => {
      try {
        return decodeURIComponent(segment)
      } catch {
        return segment
      }
    })
    .join('/')

const withoutSlash = (path: string): string => (path.length > 1 ? path.replace(/\/+$/, '') : path)

const csvCell = (value: string | number): string => {
  const text = String(value)
  return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text
}

const HEADER = (comment: string, count: number) =>
  `${comment} ${count} redirects from WordPress, generated by wp-to-payload. Review before deploying.\n`

export const formatCsv = (redirects: Redirect[]): string =>
  ['from,to,status', ...redirects.map((r) => [r.from, r.to, r.status].map(csvCell).join(','))].join(
    '\n',
  ) + '\n'

export const formatJson = (redirects: Redirect[]): string =>
  `${JSON.stringify(
    redirects.map((r) => ({
      from: r.from,
      to: r.to,
      status: r.status,
      kind: r.kind,
      ...(r.wpId === undefined ? {} : { wpId: r.wpId }),
    })),
    null,
    2,
  )}\n`

/**
 * For `redirects()` in next.config. Next.js removes the trailing slash before matching (unless
 * `trailingSlash` is on), and treats `:`, `(`, `)`, `*`, `+`, `?` and `{` in `source` as
 * pattern syntax, so those are escaped.
 */
export const formatNext = (redirects: Redirect[]): string =>
  `${JSON.stringify(
    redirects.map((r) => ({
      source: withoutSlash(r.from).replace(/[:()*+?{}]/g, (c) => `\\${c}`),
      destination: r.to,
      permanent: true,
    })),
    null,
    2,
  )}\n`

const regexEscape = (text: string): string => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const apacheQuote = (text: string): string =>
  `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`

/**
 * mod_alias `RedirectMatch` with an anchored pattern: plain `Redirect` matches prefixes, which
 * would also redirect every URL below the old one. Apache matches the decoded path.
 */
export const formatHtaccess = (redirects: Redirect[]): string =>
  HEADER('#', redirects.length) +
  '<IfModule mod_alias.c>\n' +
  redirects
    .map(
      (r) =>
        `RedirectMatch 301 ${apacheQuote(`^${regexEscape(withoutSlash(decode(r.from)))}/?$`)} ${apacheQuote(r.to)}`,
    )
    .join('\n') +
  '\n</IfModule>\n'

const nginxQuote = (text: string): string =>
  `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`

/**
 * A `map` on `$uri` (decoded and normalized by nginx) with and without the trailing slash. It
 * stays fast for thousands of entries; the comment shows the two lines to add to `server`.
 */
export const formatNginx = (redirects: Redirect[]): string => {
  const lines: string[] = []
  for (const r of redirects) {
    const from = withoutSlash(decode(r.from))
    lines.push(`    ${nginxQuote(from)} ${nginxQuote(r.to)};`)
    if (from !== '/') lines.push(`    ${nginxQuote(`${from}/`)} ${nginxQuote(r.to)};`)
  }
  return (
    HEADER('#', redirects.length) +
    '# Include this file in the http block, then add to your server block:\n' +
    '#   if ($wp_redirect) { return 301 $wp_redirect; }\n' +
    'map $uri $wp_redirect {\n' +
    '    default "";\n' +
    `${lines.join('\n')}\n` +
    '}\n'
  )
}

/** Netlify `_redirects`; Netlify ignores trailing slashes when matching. */
export const formatNetlify = (redirects: Redirect[]): string =>
  HEADER('#', redirects.length) +
  redirects.map((r) => `${withoutSlash(r.from)} ${r.to} 301`).join('\n') +
  '\n'

export const formatRedirects = (format: RedirectFormat, redirects: Redirect[]): string => {
  switch (format) {
    case 'csv':
      return formatCsv(redirects)
    case 'json':
      return formatJson(redirects)
    case 'next':
      return formatNext(redirects)
    case 'htaccess':
      return formatHtaccess(redirects)
    case 'nginx':
      return formatNginx(redirects)
    case 'netlify':
      return formatNetlify(redirects)
  }
}
